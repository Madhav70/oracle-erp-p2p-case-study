-- 1. SUPPLIERS MASTER TABLE
CREATE TABLE XXNS_SUPPLIERS (
    SUPPLIER_ID         VARCHAR2(30)    PRIMARY KEY,
    SUPPLIER_NAME       VARCHAR2(255)   NOT NULL,
    CATEGORY            VARCHAR2(100)   NOT NULL,
    PAYMENT_TERMS       VARCHAR2(50)    DEFAULT 'Net 30' NOT NULL,
    RISK_RATING         VARCHAR2(20)    CHECK (RISK_RATING IN ('Low', 'Medium', 'High')),
    LEAD_TIME_DAYS      NUMBER(5)       DEFAULT 7 NOT NULL,
    IS_ACTIVE           VARCHAR2(5)     DEFAULT 'True' CHECK (IS_ACTIVE IN ('True', 'False')),
    CREATED_DATE        DATE            DEFAULT SYSDATE NOT NULL
);

-- 2. PURCHASE REQUISITIONS TABLE
CREATE TABLE XXNS_REQUISITIONS (
    PR_ID               VARCHAR2(30)    PRIMARY KEY,
    PR_DATE             DATE            NOT NULL,
    DEPARTMENT          VARCHAR2(100)   NOT NULL,
    REQUESTER_NAME      VARCHAR2(150)   NOT NULL,
    CATEGORY            VARCHAR2(100)   NOT NULL,
    ESTIMATED_AMOUNT    NUMBER(12,2)    CHECK (ESTIMATED_AMOUNT > 0),
    APPROVAL_STATUS     VARCHAR2(30)    CHECK (APPROVAL_STATUS IN ('Approved', 'Rejected', 'Pending Approval')),
    APPROVER            VARCHAR2(150),
    APPROVAL_DATE       DATE,
    JUSTIFICATION       VARCHAR2(500)
);

-- 3. PURCHASE ORDERS TABLE
CREATE TABLE XXNS_PURCHASE_ORDERS (
    PO_ID               VARCHAR2(30)    PRIMARY KEY,
    PR_ID               VARCHAR2(30)    REFERENCES XXNS_REQUISITIONS(PR_ID),
    SUPPLIER_ID         VARCHAR2(30)    REFERENCES XXNS_SUPPLIERS(SUPPLIER_ID),
    SUPPLIER_NAME       VARCHAR2(255)   NOT NULL,
    CATEGORY            VARCHAR2(100)   NOT NULL,
    BUYER_NAME          VARCHAR2(150)   NOT NULL,
    PO_DATE             DATE            NOT NULL,
    PO_AMOUNT           NUMBER(12,2)    CHECK (PO_AMOUNT > 0),
    LINE_COUNT          NUMBER(4)       DEFAULT 1,
    PAYMENT_TERMS       VARCHAR2(50)    NOT NULL,
    MATCHING_TYPE       VARCHAR2(30)    CHECK (MATCHING_TYPE IN ('3-Way Match', '2-Way Match')),
    LEAD_TIME_DAYS      NUMBER(5),
    PO_STATUS           VARCHAR2(50)    DEFAULT 'Open - Awaiting Delivery'
);

-- 4. GOODS RECEIPTS TABLE
CREATE TABLE XXNS_RECEIPTS (
    RECEIPT_ID          VARCHAR2(30)    PRIMARY KEY,
    PO_ID               VARCHAR2(30)    REFERENCES XXNS_PURCHASE_ORDERS(PO_ID),
    SUPPLIER_ID         VARCHAR2(30)    REFERENCES XXNS_SUPPLIERS(SUPPLIER_ID),
    RECEIPT_DATE        DATE            NOT NULL,
    RECEIVING_CLERK     VARCHAR2(150)   NOT NULL,
    RECEIVED_QTY_PCT    NUMBER(5,2)     DEFAULT 100.0,
    INSPECTION_STATUS   VARCHAR2(100)   NOT NULL,
    DOCK_LOCATION       VARCHAR2(100)   NOT NULL
);

-- 5. SUPPLIER INVOICES TABLE
CREATE TABLE XXNS_INVOICES (
    INVOICE_ID          VARCHAR2(30)    PRIMARY KEY,
    PO_ID               VARCHAR2(30)    REFERENCES XXNS_PURCHASE_ORDERS(PO_ID),
    SUPPLIER_ID         VARCHAR2(30)    REFERENCES XXNS_SUPPLIERS(SUPPLIER_ID),
    SUPPLIER_NAME       VARCHAR2(255)   NOT NULL,
    SUPPLIER_INV_REF    VARCHAR2(100)   NOT NULL,
    INVOICE_DATE        DATE            NOT NULL,
    DUE_DATE            DATE            NOT NULL,
    INVOICE_AMOUNT      NUMBER(12,2)    CHECK (INVOICE_AMOUNT > 0),
    PO_AMOUNT           NUMBER(12,2)    NOT NULL,
    VARIANCE_AMOUNT     NUMBER(12,2)    DEFAULT 0.00,
    DISCOUNT_EARNED     NUMBER(12,2)    DEFAULT 0.00,
    MATCHING_TYPE       VARCHAR2(30)    NOT NULL,
    MATCH_STATUS        VARCHAR2(100)   NOT NULL,
    HOLD_REASON         VARCHAR2(500),
    HOLD_RESOLUTION     VARCHAR2(500),
    PAYMENT_STATUS      VARCHAR2(50)    CHECK (PAYMENT_STATUS IN ('Paid', 'Approved for Payment', 'On Hold')),
    PAID_DATE           DATE,
    PAYMENT_REFERENCE   VARCHAR2(100),
    CONSTRAINT UQ_SUPPLIER_INV UNIQUE (SUPPLIER_ID, SUPPLIER_INV_REF)
);

-- 6. AP HOLDS AUDIT LOG TABLE
CREATE TABLE XXNS_AP_HOLDS (
    HOLD_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_ID          VARCHAR2(30)    REFERENCES XXNS_INVOICES(INVOICE_ID),
    HOLD_LOOKUP_CODE    VARCHAR2(50)    NOT NULL,
    HOLD_REASON         VARCHAR2(500)   NOT NULL,
    HOLD_DATE           TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    RELEASE_LOOKUP_CODE VARCHAR2(50),
    RELEASE_REASON      VARCHAR2(500),
    RELEASE_DATE        TIMESTAMP,
    RELEASED_BY         VARCHAR2(150),
    STATUS              VARCHAR2(20)    DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'RELEASED'))
);

-- Create performance indexes for rapid matching queries
CREATE INDEX IDX_PO_SUPPLIER ON XXNS_PURCHASE_ORDERS(SUPPLIER_ID);
CREATE INDEX IDX_REC_PO ON XXNS_RECEIPTS(PO_ID);
CREATE INDEX IDX_INV_PO ON XXNS_INVOICES(PO_ID);
CREATE INDEX IDX_INV_STATUS ON XXNS_INVOICES(PAYMENT_STATUS, MATCH_STATUS);
